const (
	profileURL         = "https://hloth.dev/profile.json"
	signingFingerprint = "036F7D224297D873A4FCE9DA299E9A450132A28C"
	signingKeyPath     = "tools/sync-profile/signing-key.asc"
	profilePath        = "data/profile.json"
	donatePath         = "data/donate.txt"
	maxDownload        = 1 << 20
	wrapWidth          = 76
	gridColumns        = 3
	defaultLinkStyle   = "40;37"
	generatedNote      = "# Generated by tools/sync-profile from data/. Change the website, then sync."
)

var linkStyles = map[string]string{
	"upwork":    "40;37",
	"forgejo":   "48;5;234;38;5;202",
	"linkedin":  "48;5;25;37",
	"matrix":    "48;5;36;37",
	"telegram":  "48;5;38;37",
	"discord":   "48;5;63;37",
	"email":     "48;5;33;38;5;255",
	"blog":      "40;38;5;187",
	"instagram": "48;5;197;38;5;255",
}

var idPattern = regexp.MustCompile(`^[a-z0-9][a-z0-9-]*$`)

type link struct {
	ID        string `json:"id"`
	Label     string `json:"label"`
	Title     string `json:"title"`
	URL       string `json:"url"`
	Highlight bool   `json:"highlight"`
}

type project struct {
	ID      string `json:"id"`
	Kind    string `json:"kind"`
	Name    string `json:"name"`
	Summary string `json:"summary"`
	URL     string `json:"url"`
}

type profile struct {
	Name     string `json:"name"`
	Role     string `json:"role"`
	Location string `json:"location"`
	Birthday struct {
		Year           int `json:"year"`
		Month          int `json:"month"`
		Day            int `json:"day"`
		UTCOffsetHours int `json:"utcOffsetHours"`
	} `json:"birthday"`
	Summary string `json:"summary"`
	About   struct {
		Title      string   `json:"title"`
		Subtitle   string   `json:"subtitle"`
		Paragraphs []string `json:"paragraphs"`
	} `json:"about"`
	Links    []link    `json:"links"`
	Showcase []project `json:"showcase"`
	Donate   struct {
		URL        string `json:"url"`
		SignedText string `json:"signedText"`
	} `json:"donate"`
}

func main() {
	offline := flag.Bool("offline", false, "render from data/ without fetching")
	source := flag.String("url", profileURL, "where to fetch profile.json")
	flag.Parse()
	if err := run(*offline, *source); err != nil {
		fmt.Fprintln(os.Stderr, "sync-profile:", err)
		os.Exit(1)
	}
}

func run(offline bool, source string) error {
	if _, err := os.Stat("guest-chroot/bin/guest-shell.sh"); err != nil {
		return errors.New("run it from the repository root")
	}
	if !offline {
		if err := download(source); err != nil {
			return err
		}
	}
	p, err := readProfile()
	if err != nil {
		return err
	}
	signed, err := readSignedDonations()
	if err != nil {
		return err
	}
	files := map[string]string{
		"guest-chroot/bin/card.sh":              renderCard(p),
		"guest-chroot/screens/donate.sh":        renderDonate(p, signed),
		"guest-chroot/screens/me/about.sh":      renderAbout(p),
		"guest-chroot/screens/showcase.sh":      renderShowcase(p),
		"guest-chroot/screens/showcase/help.sh": renderShowcaseHelp(p),
	}
	for _, item := range p.Showcase {
		files["guest-chroot/screens/showcase/"+item.ID+".sh"] = renderProject(item)
	}
	if err := removeStaleShowcase(files); err != nil {
		return err
	}
	for path, content := range files {
		if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
			return err
		}
	}
	fmt.Printf("wrote %d screens from %s and %s\n", len(files), profilePath, donatePath)
	return nil
}

func download(source string) error {
	raw, err := fetch(source)
	if err != nil {
		return err
	}
	var p profile
	if err := json.Unmarshal(raw, &p); err != nil {
		return fmt.Errorf("%s: %w", source, err)
	}
	if err := validate(p); err != nil {
		return fmt.Errorf("%s: %w", source, err)
	}
	signedURL, err := url.Parse(p.Donate.SignedText)
	if err != nil || signedURL.Scheme != "https" {
		return fmt.Errorf("donate.signedText must be an https URL: %q", p.Donate.SignedText)
	}
	signed, err := fetch(p.Donate.SignedText)
	if err != nil {
		return err
	}
	pending := donatePath + ".new"
	if err := os.WriteFile(pending, signed, 0o644); err != nil {
		return err
	}
	defer os.Remove(pending)
	if err := verifySignature(pending); err != nil {
		return err
	}
	var pretty bytes.Buffer
	if err := json.Indent(&pretty, raw, "", "\t"); err != nil {
		return err
	}
	pretty.WriteByte('\n')
	if err := os.WriteFile(profilePath, pretty.Bytes(), 0o644); err != nil {
		return err
	}
	return os.Rename(pending, donatePath)
}

func fetch(target string) ([]byte, error) {
	client := &http.Client{Timeout: 30 * time.Second}
	response, err := client.Get(target)
	if err != nil {
		return nil, err
	}
	defer response.Body.Close()
	if response.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("%s: HTTP %d", target, response.StatusCode)
	}
	body, err := io.ReadAll(io.LimitReader(response.Body, maxDownload+1))
	if err != nil {
		return nil, err
	}
	if len(body) > maxDownload {
		return nil, fmt.Errorf("%s: larger than %d bytes", target, maxDownload)
	}
	return body, nil
}

func readProfile() (profile, error) {
	var p profile
	raw, err := os.ReadFile(profilePath)
	if err != nil {
		return p, err
	}
	if err := json.Unmarshal(raw, &p); err != nil {
		return p, fmt.Errorf("%s: %w", profilePath, err)
	}
	if err := validate(p); err != nil {
		return p, fmt.Errorf("%s: %w", profilePath, err)
	}
	return p, nil
}

func readSignedDonations() (string, error) {
	raw, err := os.ReadFile(donatePath)
	if err != nil {
		return "", err
	}
	text := strings.TrimRight(strings.ReplaceAll(string(raw), "\r\n", "\n"), "\n")
	if !strings.HasPrefix(text, "-----BEGIN PGP SIGNED MESSAGE-----\n") ||
		!strings.HasSuffix(text, "\n-----END PGP SIGNATURE-----") {
		return "", fmt.Errorf("%s must be exactly one clearsigned message", donatePath)
	}
	for _, line := range strings.Split(text, "\n") {
		if err := checkText(donatePath, line); err != nil {
			return "", err
		}
	}
	if err := verifySignature(donatePath); err != nil {
		return "", err
	}
	return text, nil
}

func verifySignature(path string) error {
	home, err := os.MkdirTemp("", "sync-profile-gnupg-")
	if err != nil {
		return err
	}
	defer os.RemoveAll(home)
	defer exec.Command("gpgconf", "--homedir", home, "--kill", "all").Run()
	if output, err := exec.Command("gpg", "--batch", "--quiet", "--homedir", home, "--import", signingKeyPath).CombinedOutput(); err != nil {
		return fmt.Errorf("importing %s: %w\n%s", signingKeyPath, err, output)
	}
	status, err := exec.Command("gpg", "--batch", "--homedir", home, "--status-fd", "1", "--verify", path).Output()
	if err != nil {
		return fmt.Errorf("%s has no valid signature: %w", path, err)
	}
	good, primary := false, ""
	for _, line := range strings.Split(string(status), "\n") {
		fields := strings.Fields(line)
		if len(fields) < 2 || fields[0] != "[GNUPG:]" {
			continue
		}
		switch fields[1] {
		case "GOODSIG":
			good = true
		case "VALIDSIG":
			primary = fields[len(fields)-1]
		}
	}
	if !good || primary != signingFingerprint {
		return fmt.Errorf("%s is not signed by %s", path, signingFingerprint)
	}
	return nil
}

func validate(p profile) error {
	texts := map[string]string{
		"name": p.Name, "role": p.Role, "location": p.Location, "summary": p.Summary,
		"about.title": p.About.Title, "about.subtitle": p.About.Subtitle,
	}
	for field, value := range texts {
		if err := checkText(field, value); err != nil {
			return err
		}
	}
	b := p.Birthday
	if b.Year < 1900 || b.Month < 1 || b.Month > 12 || b.Day < 1 || b.Day > 31 || b.UTCOffsetHours < -12 || b.UTCOffsetHours > 14 {
		return fmt.Errorf("birthday is out of range: %+v", b)
	}
	if len(p.About.Paragraphs) == 0 {
		return errors.New("about.paragraphs is empty")
	}
	for i, paragraph := range p.About.Paragraphs {
		if err := checkText(fmt.Sprintf("about.paragraphs[%d]", i), paragraph); err != nil {
			return err
		}
	}
	if len(p.Links) == 0 {
		return errors.New("links is empty")
	}
	seen := map[string]bool{}
	for _, l := range p.Links {
		if !idPattern.MatchString(l.ID) || seen["link:"+l.ID] {
			return fmt.Errorf("bad or repeated link id %q", l.ID)
		}
		seen["link:"+l.ID] = true
		for field, value := range map[string]string{"label": l.Label, "title": l.Title} {
			if err := checkText("links."+l.ID+"."+field, value); err != nil {
				return err
			}
		}
		if err := checkURL("links."+l.ID+".url", l.URL, "https", "http", "mailto"); err != nil {
			return err
		}
	}
	for _, item := range p.Showcase {
		if !idPattern.MatchString(item.ID) || item.ID == "help" || seen["showcase:"+item.ID] {
			return fmt.Errorf("bad or repeated showcase id %q", item.ID)
		}
		seen["showcase:"+item.ID] = true
		if item.Kind != "website" && item.Kind != "project" {
			return fmt.Errorf("showcase %s: unknown kind %q", item.ID, item.Kind)
		}
		for field, value := range map[string]string{"name": item.Name, "summary": item.Summary} {
			if err := checkText("showcase."+item.ID+"."+field, value); err != nil {
				return err
			}
		}
		if err := checkURL("showcase."+item.ID+".url", item.URL, "https", "http"); err != nil {
			return err
		}
	}
	if err := checkURL("donate.url", p.Donate.URL, "https", "http"); err != nil {
		return err
	}
	return checkURL("donate.signedText", p.Donate.SignedText, "https", "http")
}

func checkText(field, value string) error {
	if strings.TrimSpace(value) == "" && field != donatePath {
		return fmt.Errorf("%s is empty", field)
	}
	if !utf8.ValidString(value) {
		return fmt.Errorf("%s is not valid UTF-8", field)
	}
	for _, r := range value {
		if r < 0x20 || (r >= 0x7f && r < 0xa0) || (r >= 0x202a && r <= 0x202e) || (r >= 0x2066 && r <= 0x2069) || r == 0x200b || r == 0xfeff {
			return fmt.Errorf("%s contains a control or invisible character U+%04X", field, r)
		}
	}
	return nil
}

func checkURL(field, value string, schemes ...string) error {
	if err := checkText(field, value); err != nil {
		return err
	}
	parsed, err := url.Parse(value)
	if err != nil {
		return fmt.Errorf("%s: %w", field, err)
	}
	for _, scheme := range schemes {
		if parsed.Scheme == scheme {
			return nil
		}
	}
	return fmt.Errorf("%s: scheme %q is not allowed", field, parsed.Scheme)
}

func quote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

func width(s string) int {
	return utf8.RuneCountInString(s)
}

func wrap(text string, limit int) []string {
	return wrapWords(strings.Fields(text), limit, " ")
}

func wrapWords(words []string, limit int, separator string) []string {
	var lines []string
	line := ""
	for _, word := range words {
		if line != "" && width(line)+width(separator)+width(word) > limit {
			lines = append(lines, line)
			line = ""
		}
		if line != "" {
			line += separator
		}
		line += word
	}
	if line != "" {
		lines = append(lines, line)
	}
	return lines
}

func displayURL(raw string) string {
	parsed, err := url.Parse(raw)
	if err != nil || parsed.Host == "" {
		return raw
	}
	return strings.TrimSuffix(parsed.Host+parsed.Path, "/")
}

func hyperlink(target, text string) string {
	return fmt.Sprintf("printf '\\033]8;;%%s\\033\\\\%%s\\033]8;;\\033\\\\\\n' %s %s\n", quote(target), quote(text))
}

func script(rootUp string, body string) string {
	var b strings.Builder
	b.WriteString("#!/bin/dash\n" + generatedNote + "\n")
	if rootUp != "" {
		fmt.Fprintf(&b, "ROOT_DIR=\"$(cd \"$(dirname \"$0\")/%s\" && pwd)\"\n. \"$ROOT_DIR/bin/utils.sh\"\n", rootUp)
	}
	b.WriteString("\n" + body)
	return b.String()
}

func renderCard(p profile) string {
	b := p.Birthday
	ageSuffix := " y.o., " + p.Location
	cardWidth := max(width(p.Name), width(p.Role), 2+width(ageSuffix)) + 2

	labels := make([]string, len(p.Links))
	for i, l := range p.Links {
		labels[i] = l.Label
		if l.Highlight {
			labels[i] += "°"
		}
	}
	rows := (len(p.Links) + gridColumns - 1) / gridColumns
	columnWidths := make([]int, gridColumns)
	for i, label := range labels {
		column := i / rows
		columnWidths[column] = max(columnWidths[column], width(label)+2)
	}
	gridWidth := gridColumns - 1
	for _, w := range columnWidths {
		gridWidth += w
	}
	inner := max(cardWidth, gridWidth)
	columnWidths[gridColumns-1] += inner - gridWidth

	pad := func(used int) string { return strings.Repeat(" ", inner-2-used) }
	rule := func(left, join, right string) string {
		parts := make([]string, gridColumns)
		for i, w := range columnWidths {
			parts[i] = strings.Repeat("─", w)
		}
		return left + strings.Join(parts, join) + right
	}

	var body strings.Builder
	fmt.Fprintf(&body, "read -r year monthday <<EOF\n$(TZ=UTC%+d date '+%%Y 1%%m%%d')\nEOF\n", -b.UTCOffsetHours)
	fmt.Fprintf(&body, "age=$((year - %d - (monthday < 1%02d%02d)))\n\n", b.Year, b.Month, b.Day)
	fmt.Fprintf(&body, "printf '%%s\\n' %s\n", quote("╭"+strings.Repeat("─", inner)+"╮"))
	fmt.Fprintf(&body, "printf '│ \\033[1m%%s\\033[0m%%s │\\n' %s %s\n", quote(p.Name), quote(pad(width(p.Name))))
	fmt.Fprintf(&body, "printf '│ %%s%%s │\\n' %s %s\n", quote(p.Role), quote(pad(width(p.Role))))
	fmt.Fprintf(&body, "printf '│ \\033[2m%%s%%s\\033[0m%%s │\\n' \"$age\" %s %s\n", quote(ageSuffix), quote(pad(2+width(ageSuffix))))
	fmt.Fprintf(&body, "printf '%%s\\n' %s\n", quote("╰"+strings.Repeat("─", inner)+"╯"))
	fmt.Fprintf(&body, "printf '%%s\\n' %s\n", quote(rule("╭", "┬", "╮")))
	for row := range rows {
		format := "│"
		var args []string
		for column := range gridColumns {
			i := column*rows + row
			if i >= len(p.Links) {
				format += strings.Repeat(" ", columnWidths[column]) + "│"
				continue
			}
			style := linkStyles[p.Links[i].ID]
			if style == "" {
				style = defaultLinkStyle
			}
			format += `\033]8;;%s\033\\\033[` + style + `m%s\033[0m\033]8;;\033\\│`
			cell := " " + labels[i] + strings.Repeat(" ", columnWidths[column]-1-width(labels[i]))
			args = append(args, quote(p.Links[i].URL), quote(cell))
		}
		fmt.Fprintf(&body, "printf '%s\\n' %s\n", format, strings.Join(args, " "))
	}
	fmt.Fprintf(&body, "printf '%%s\\n' %s\n", quote(rule("╰", "┴", "╯")))
	return script("", body.String())
}

func fingerprintGroups(fingerprint string) string {
	var groups []string
	for i := 0; i < len(fingerprint); i += 4 {
		groups = append(groups, fingerprint[i:i+4])
	}
	return strings.Join(groups[:5], " ") + "  " + strings.Join(groups[5:], " ")
}

func renderDonate(p profile, signed string) string {
	var body strings.Builder
	fmt.Fprintf(&body, "printf '\\033[1m%%s\\033[0m\\n' %s\n", quote("Donate"))
	fmt.Fprintf(&body, "printf '%%s\\n%%s\\n\\n' %s %s\n", quote("My donation addresses, signed with my PGP key"), quote(fingerprintGroups(signingFingerprint)))
	fmt.Fprintf(&body, "printf '%%s\\n\\n' %s\n", quote(signed))
	body.WriteString("printf '%s ' 'All options:'\n")
	body.WriteString(hyperlink(p.Donate.URL, displayURL(p.Donate.URL)))
	return script("", body.String())
}

func renderAbout(p profile) string {
	var body strings.Builder
	body.WriteString("set_tab_title \"hloth.dev/me/about\"\n")
	fmt.Fprintf(&body, "printf '\\033[1m%%s\\033[0m\\n\\033[2m%%s\\033[0m\\n' %s %s\n", quote(p.About.Title), quote(p.About.Subtitle))
	for _, paragraph := range p.About.Paragraphs {
		fmt.Fprintf(&body, "printf '\\n%%s\\n' %s\n", quote(strings.Join(wrap(paragraph, wrapWidth), "\n")))
	}
	return script("../..", body.String())
}

func idList(p profile, kind string) []string {
	var ids []string
	for _, item := range p.Showcase {
		if item.Kind == kind {
			ids = append(ids, item.ID)
		}
	}
	return ids
}

func renderShowcase(p profile) string {
	var body strings.Builder
	body.WriteString("set_tab_title \"hloth.dev/showcase\"\nset_tab_color 113 32 193\n")
	for _, group := range []struct{ kind, title string }{{"website", "Websites"}, {"project", "Projects"}} {
		ids := idList(p, group.kind)
		if len(ids) == 0 {
			continue
		}
		fmt.Fprintf(&body, "printf '\\033[1m%%s\\033[0m\\n' %s\n", quote(group.title))
		for _, line := range wrapWords(ids, wrapWidth-2, "  ") {
			fmt.Fprintf(&body, "printf '  %%s\\n' %s\n", quote(line))
		}
	}
	fmt.Fprintf(&body, "printf '%%s\\n' %s\n", quote("Type a name to open it, or 'help' for descriptions."))
	return script("..", body.String())
}

func renderShowcaseHelp(p profile) string {
	longest := 0
	for _, item := range p.Showcase {
		longest = max(longest, width(item.ID))
	}
	var body strings.Builder
	for _, item := range p.Showcase {
		fmt.Fprintf(&body, "printf '\\033[1m%%s\\033[0m%%s  %%s\\n' %s %s %s\n", quote(item.ID), quote(strings.Repeat(" ", longest-width(item.ID))), quote(item.Name))
	}
	return script("../..", body.String())
}

func renderProject(item project) string {
	var body strings.Builder
	fmt.Fprintf(&body, "set_tab_title %s\n", quote("hloth.dev/showcase/"+item.ID))
	fmt.Fprintf(&body, "printf '\\033[1m%%s\\033[0m \\033[2m%%s\\033[0m\\n' %s %s\n", quote(item.Name), quote(item.Kind))
	fmt.Fprintf(&body, "printf '%%s\\n' %s\n", quote(strings.Join(wrap(item.Summary, wrapWidth), "\n")))
	body.WriteString(hyperlink(item.URL, displayURL(item.URL)))
	return script("../..", body.String())
}

func removeStaleShowcase(files map[string]string) error {
	existing, err := filepath.Glob("guest-chroot/screens/showcase/*.sh")
	if err != nil {
		return err
	}
	for _, path := range existing {
		if _, keep := files[path]; !keep {
			if err := os.Remove(path); err != nil {
				return err
			}
		}
	}
	return nil
}
